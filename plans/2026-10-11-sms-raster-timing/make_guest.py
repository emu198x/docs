from pathlib import Path
import sys
reload=int(sys.argv[1]); out=Path(sys.argv[2]); assert 0<=reload<=255
rom=bytearray(32768)
rom[:3]=bytes([0xc3,0,1]) # JP $0100
# ISR: record V count and status in RAM rings, then alternate backdrop colours.
isr=bytes([
 0xf5,0xe5, # PUSH AF,HL
 0x3a,0,0xc0,0x6f,0x26,0xc1, # LD A,(C000); L=A; H=C1
 0xdb,0x7e,0x77, # IN A,(7E); LD (HL),A
 0x26,0xc2,0xdb,0xbf,0x77, # H=C2; IN A,(BF); LD (HL),A (ack)
 0x7d,0x3c,0x32,0,0xc0, # A=L; INC A; LD (C000),A
 0xe6,1,0xc6,1,0xd3,0xbf, # AND 1; ADD 1; OUT (BF),A
 0x3e,0x87,0xd3,0xbf, # R7=colour
 0xe1,0xf1,0xfb,0xed,0x4d]) # POP HL,AF; EI; RETI
rom[0x38:0x38+len(isr)]=isr
c=bytearray([0xf3,0x31,0xf0,0xdf]) # DI; SP=DFF0
# Clear IRQ observation rings; RAM writes through real guest instructions.
c+=bytes([0xaf,0x21,0,0xc0,0x11,1,0xc0,0x01,0xff,2,0x77,0xed,0xb0])
def output(port,value): c.extend([0x3e,value,0xd3,port])
def reg(n,value): output(0xbf,value); output(0xbf,0x80|n)
reg(0,4); reg(1,0); reg(2,0x0e); reg(5,0x7e); reg(7,1); reg(8,0); reg(9,0); reg(10,reload)
# Zero 16 KB VRAM. Preserve BC around the CPU-loop decrement test.
output(0xbf,0); output(0xbf,0x40)
c+=bytes([0x01,0,0x40]); loop=0x100+len(c)
c+=bytes([0xaf,0xd3,0xbe,0x0b,0x78,0xb1,0xc2,loop&255,loop>>8])
# Stop sprite list at first entry.
output(0xbf,0); output(0xbf,0x7f); output(0xbe,0xd0)
# Backdrop palette entries 17=red,18=green.
output(0xbf,17); output(0xbf,0xc0); output(0xbe,3); output(0xbe,12)
reg(1,0x40); c+=bytes([0xdb,0xbf]); reg(0,0x14)
c+=bytes([0xed,0x56,0xfb]); halt=0x100+len(c); c+=bytes([0x76,0xc3,halt&255,halt>>8])
rom[0x100:0x100+len(c)]=c
rom[0x7ff0:0x7ff8]=b'TMR SEGA'; rom[0x7fff]=0x4c # export SMS,32KB
checksum=sum(rom[:0x7ff0])&65535;rom[0x7ffa:0x7ffc]=checksum.to_bytes(2,'little')
out.write_bytes(rom)
print(f'guest reload={reload} setup_bytes={len(c)} isr_bytes={len(isr)} checksum={checksum:04x}')
